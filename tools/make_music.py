#!/usr/bin/env python3
"""Composes the chapter battle themes in assets/music/ (mono, 22.05 kHz;
the game resamples on load). Developer tool, needs numpy.

    python3 tools/make_music.py            # all tracks
    python3 tools/make_music.py frost      # one track

The original title and meadow battle tracks are generated by the game
itself (asset_bootstrap.cpp); these add a theme per chapter group:
  frost    - Frostpeak Highlands, Glacial Bastion
  volcano  - Obsidian Citadel, Magma Foundry
  mystic   - Bamboo Steppes, Sunken Ruins, Solstice Sanctuary, the vaults
  heroic   - Zephyr Highlands, Thunderhead Peaks, Colosseum, Sovereign Sanctum
"""
import os
import sys
import wave

import numpy as np

SR = 22050
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'music')
rng = np.random.default_rng(7)

NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']
SCALES = {'minor': [0, 2, 3, 5, 7, 8, 10], 'dorian': [0, 2, 3, 5, 7, 9, 10],
          'harmonic': [0, 2, 3, 5, 7, 8, 11], 'major': [0, 2, 4, 5, 7, 9, 11]}


def midi_hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)


class Key:
    def __init__(self, root_name, octave, scale):
        self.root = NOTE_NAMES.index(root_name) + 12 * (octave + 1)
        self.steps = SCALES[scale]

    def deg(self, d, octave=0):
        """Scale degree (0-based, may exceed 6 or go negative) -> MIDI."""
        o, i = divmod(d, 7)
        return self.root + 12 * (o + octave) + self.steps[i]

    def triad(self, d, octave=0):
        return [self.deg(d, octave), self.deg(d + 2, octave), self.deg(d + 4, octave)]


# ----------------------------------------------------------------- DSP

def tax(dur):
    return np.arange(int(dur * SR)) / SR


def fft_filter(x, lo=None, hi=None, order=2):
    """Zero-phase Butterworth-magnitude band filter via FFT (static)."""
    n = len(x)
    nfft = 1 << (n - 1).bit_length()
    X = np.fft.rfft(x, nfft)
    f = np.fft.rfftfreq(nfft, 1 / SR)
    g = np.ones_like(f)
    if hi:
        g *= 1 / np.sqrt(1 + (f / hi) ** (2 * order))
    if lo:
        g *= 1 / np.sqrt(1 + (lo / np.maximum(f, 1e-3)) ** (2 * order))
    return np.fft.irfft(X * g, nfft)[:n]


def env(dur, a=0.005, d=0.1, s=0.7, r=0.1):
    t = tax(dur)
    e = np.where(t < a, t / a, np.where(t < a + d, 1 - (1 - s) * (t - a) / d, s))
    return e * np.clip((dur - t) / r, 0, 1)


def phase(freq, dur):
    n = int(dur * SR)
    f = np.broadcast_to(np.asarray(freq, dtype=float), (n,))
    return 2 * np.pi * np.cumsum(f) / SR


def saw(freq, dur):
    p = phase(freq, dur) / (2 * np.pi)
    return 2 * (p % 1.0) - 1


def reverb(x, size=1.6, mix=0.25, damp=5000):
    n = int(size * SR)
    t = np.arange(n) / SR
    ir = fft_filter(rng.standard_normal(n) * np.exp(-t * 6.9 / size), hi=damp)
    ir[: int(0.02 * SR)] = 0
    ir /= np.sqrt((ir ** 2).sum()) + 1e-9
    m = len(x) + n
    nfft = 1 << (m - 1).bit_length()
    wet = np.fft.irfft(np.fft.rfft(x, nfft) * np.fft.rfft(ir, nfft), nfft)[:m]
    # Wrap the tail onto the start so the loop is seamless.
    out = x.copy() * (1 - mix)
    wet *= mix * 2.0
    out += wet[: len(x)]
    out[: n] += wet[len(x):len(x) + n][: len(out[:n])]
    return out


# ----------------------------------------------------------------- instruments

def bell(m, dur, vel=1.0):
    f = midi_hz(m)
    t = tax(dur)
    parts = [(1, 1.0, 1.2), (2.0, 0.4, 0.6), (3.0, 0.2, 0.35), (4.16, 0.12, 0.2), (5.43, 0.06, 0.12)]
    out = sum(a * np.sin(2 * np.pi * f * r * t) * np.exp(-t / d) for r, a, d in parts)
    return out * vel * np.clip(t / 0.002, 0, 1)


def marimba(m, dur, vel=1.0):
    f = midi_hz(m)
    t = tax(dur)
    out = np.sin(2 * np.pi * f * t) * np.exp(-t * 6) + 0.25 * np.sin(2 * np.pi * f * 3.98 * t) * np.exp(-t * 30)
    return out * vel * np.clip(t / 0.003, 0, 1)


def pluck(m, dur, vel=1.0, bright=1.0):
    f = midi_hz(m)
    t = tax(dur)
    out = np.zeros_like(t)
    for h in range(1, 8):
        out += (1.0 / h ** (1.3 / bright)) * np.sin(2 * np.pi * f * h * t) * np.exp(-t * (3 + h * 2.2))
    return out * vel * np.clip(t / 0.003, 0, 1)


def pad(chord, dur, vel=1.0, bright=1800):
    out = np.zeros(int(dur * SR))
    t = tax(dur)
    for m in chord:
        f = midi_hz(m)
        for det in (-0.006, 0.0, 0.007):
            out += saw(f * (1 + det) * (1 + 0.002 * np.sin(2 * np.pi * 4.5 * t)), dur)
    out = fft_filter(out, hi=bright, order=2)
    return out * env(dur, 0.25, 0.3, 0.8, 0.4) * vel / (3 * len(chord))


def strings_stab(chord, dur, vel=1.0):
    out = np.zeros(int(dur * SR))
    for m in chord:
        out += saw(midi_hz(m), dur) + saw(midi_hz(m) * 1.004, dur)
    out = fft_filter(out, lo=150, hi=3200)
    return out * env(dur, 0.006, 0.05, 0.5, 0.06) * vel / (2 * len(chord))


def brass(m, dur, vel=1.0):
    f = midi_hz(m)
    t = tax(dur)
    vib = 1 + 0.004 * np.sin(2 * np.pi * 5.2 * t) * np.clip(t / 0.3, 0, 1)
    raw = saw(f * vib, dur) + 0.6 * saw(f * 1.003 * vib, dur)
    e = env(dur, 0.04, 0.12, 0.8, 0.08)
    # Brighter while loud: blend a bright and a dark copy by envelope.
    bright = fft_filter(raw, hi=3500)
    dark = fft_filter(raw, hi=900)
    return (dark * (1 - e) + bright * e) * e * vel * 0.4


def flute(m, dur, vel=1.0):
    f = midi_hz(m)
    t = tax(dur)
    vib = 1 + 0.006 * np.sin(2 * np.pi * 5.0 * t) * np.clip((t - 0.15) / 0.3, 0, 1)
    tone = np.sin(phase(f * vib, dur)) + 0.18 * np.sin(2 * phase(f * vib, dur))
    breath = fft_filter(rng.standard_normal(len(t)), lo=f * 0.8, hi=f * 3) * 0.08
    return (tone + breath) * env(dur, 0.06, 0.1, 0.85, 0.1) * vel * 0.5


def bass(m, dur, vel=1.0, grit=1.0):
    f = midi_hz(m)
    t = tax(dur)
    tone = np.sin(phase(f, dur)) + 0.3 * np.sin(2 * phase(f, dur))
    tone = np.tanh(tone * (1 + grit)) / np.tanh(1 + grit)
    return tone * env(dur, 0.005, 0.08, 0.75, 0.05) * vel


def kick(vel=1.0):
    dur = 0.35
    t = tax(dur)
    f = 50 + 110 * np.exp(-t * 30)
    return np.sin(phase(f, dur)) * np.exp(-t * 9) * vel


def snare(vel=1.0):
    dur = 0.22
    t = tax(dur)
    body = np.sin(phase(190, dur)) * np.exp(-t * 25)
    rattle = fft_filter(rng.standard_normal(len(t)), lo=1200, hi=7000) * np.exp(-t * 16)
    return (0.6 * body + 0.8 * rattle) * vel


def hat(vel=1.0, open_=False):
    dur = 0.25 if open_ else 0.05
    t = tax(dur)
    n = fft_filter(rng.standard_normal(len(t)), lo=6000)
    return n * np.exp(-t * (12 if open_ else 70)) * vel * 0.5


def tom(m, vel=1.0):
    dur = 0.4
    t = tax(dur)
    f = midi_hz(m) * (1 + 0.6 * np.exp(-t * 25))
    return np.sin(phase(f, dur)) * np.exp(-t * 7) * vel


def shaker(vel=1.0):
    dur = 0.07
    t = tax(dur)
    return fft_filter(rng.standard_normal(len(t)), lo=4000, hi=9000) * np.sin(np.pi * t / dur) * vel * 0.4


# ----------------------------------------------------------------- sequencing

class Track:
    def __init__(self, bpm, bars, beats_per_bar=4):
        self.beat = 60.0 / bpm
        self.bars = bars
        self.bpb = beats_per_bar
        self.len = int(bars * beats_per_bar * self.beat * SR)
        self.buses = {}

    def at(self, bar, beat):
        return int(((bar * self.bpb) + beat) * self.beat * SR)

    def add(self, bus, sig, bar, beat, gain=1.0):
        buf = self.buses.setdefault(bus, np.zeros(self.len + SR * 4))
        i = self.at(bar, beat)
        buf[i:i + len(sig)] += sig * gain

    def mix(self, levels, wet):
        out = np.zeros(self.len)
        rev_in = np.zeros(self.len)
        for bus, buf in self.buses.items():
            body = buf[: self.len].copy()
            tail = buf[self.len:]
            body[: len(tail)] += tail[: self.len]  # wrap note tails for looping
            g = levels.get(bus, 1.0)
            out += body * g
            rev_in += body * g * wet.get(bus, 0.0)
        out += reverb(rev_in, 1.8, 1.0) * 0.5
        return out


def master(x, target_rms_db=-17.0):
    x = fft_filter(x, lo=30, hi=9500)
    rms = np.sqrt(np.mean(x ** 2)) + 1e-9
    x = x * (10 ** (target_rms_db / 20) / rms)
    x = np.tanh(x * 1.4) / 1.4  # gentle glue/limiting
    pk = np.abs(x).max()
    if pk > 0.89:
        x *= 0.89 / pk
    # Nudge the last few ms so the loop point joins without a click.
    k = 256
    x[-k:] += (x[0] - x[-1]) * np.linspace(0, 1, k)
    return x


def play_melody(tr, bus, inst, key, notes, start_bar, octave=1, vel=0.8, gap=0.92):
    """notes: list of (degree or None, beats)."""
    total = sum(b for _, b in notes)
    end_bar = start_bar + total / tr.bpb
    if total % tr.bpb or end_bar > tr.bars:
        print(f'    warning: melody of {total} beats from bar {start_bar} ends at bar {end_bar} (loop is {tr.bars})')
    pos = 0.0
    for d, beats in notes:
        if d is not None:
            bar = start_bar + int(pos // tr.bpb)
            beat = pos % tr.bpb
            tr.add(bus, inst(key.deg(d, octave), beats * tr.beat * gap, vel), bar, beat)
        pos += beats


# ----------------------------------------------------------------- tracks

def frost():
    key = Key('D', 3, 'minor')
    tr = Track(bpm=84, bars=16)
    prog = [0, 5, 2, 6, 0, 5, 3, 4] * 2          # Dm Bb F C | Dm Bb Gm A(m)
    for bar, d in enumerate(prog):
        ch = key.triad(d)
        tr.add('pad', pad([m + 12 for m in ch], 4 * tr.beat, 0.9, bright=1400), bar, 0)
        tr.add('bass', bass(key.deg(d, -1), 3.5 * tr.beat, 0.7, grit=0.2), bar, 0)
        arp = ch + [ch[1] + 12, ch[2] + 12, ch[1] + 12, ch[0] + 12, ch[2]]
        for i in range(8):
            tr.add('arp', bell(arp[i] + 12, 1.2, 0.35 if i % 2 else 0.45), bar, i * 0.5)
        if bar >= 4:
            tr.add('perc', hat(0.25), bar, 1.0)
            tr.add('perc', hat(0.25), bar, 3.0)
            tr.add('perc', kick(0.5), bar, 0)
    a = [(4, 1.5), (3, 0.5), (2, 1), (0, 1), (1, 1.5), (2, 0.5), (4, 2), (None, 2),
         (5, 1.5), (4, 0.5), (2, 1), (1, 1), (0, 2)]
    b = [(7, 1.5), (6, 0.5), (4, 1), (5, 1), (4, 1.5), (2, 0.5), (1, 2), (None, 2),
         (2, 1.5), (3, 0.5), (4, 1), (6, 1), (7, 2)]
    play_melody(tr, 'lead', bell, key, a + b, 8, octave=1, vel=0.7)
    x = tr.mix({'pad': 0.9, 'bass': 0.8, 'arp': 0.5, 'lead': 0.75, 'perc': 0.6},
               {'pad': 0.5, 'arp': 0.6, 'lead': 0.5, 'perc': 0.2})
    return master(x, -18)


def volcano():
    key = Key('E', 2, 'harmonic')
    tr = Track(bpm=124, bars=16)
    prog = [0, 5, 3, 4] * 4                          # Em C Am B
    for bar, d in enumerate(prog):
        ch = key.triad(d)
        for e in range(8):  # driving eighth-note bass
            tr.add('bass', bass(key.deg(d, 0), 0.45 * tr.beat, 0.8 if e % 2 == 0 else 0.6, grit=1.6), bar, e * 0.5)
        for beat in (0, 1.5, 3):
            tr.add('stab', strings_stab([m + 12 for m in ch], 0.35 * tr.beat, 0.8), bar, beat)
        tr.add('drums', kick(1.0), bar, 0)
        tr.add('drums', kick(0.8), bar, 2.5)
        tr.add('drums', snare(0.8), bar, 1)
        tr.add('drums', snare(0.8), bar, 3)
        for e in range(8):
            tr.add('drums', hat(0.35 if e % 2 else 0.2), bar, e * 0.5)
        if bar % 4 == 3:
            for i, mm in enumerate([key.deg(4, 1), key.deg(2, 1), key.deg(0, 1), key.deg(-2, 1)]):
                tr.add('drums', tom(mm, 0.8), bar, 2 + i * 0.5)
    hook = [(0, 1), (2, 0.5), (4, 1.5), (3, 0.5), (2, 0.5), (1, 1), (2, 1), (None, 2),
            (5, 1), (4, 0.5), (2, 1.5), (1, 0.5), (0, 0.5), (-1, 1), (0, 1), (None, 2)]
    play_melody(tr, 'lead', brass, key, hook, 4, octave=2, vel=0.9)
    play_melody(tr, 'lead', brass, key, hook, 12, octave=2, vel=0.9)
    x = tr.mix({'bass': 0.65, 'stab': 0.5, 'drums': 0.75, 'lead': 0.8},
               {'stab': 0.3, 'drums': 0.15, 'lead': 0.35})
    return master(x, -16)


def mystic():
    key = Key('A', 3, 'minor')
    tr = Track(bpm=92, bars=16)
    prog = [0, 6, 5, 6, 0, 4, 5, 4]                 # Am G F G | Am Em F E(m)
    prog = prog * 2
    for bar, d in enumerate(prog):
        ch = key.triad(d)
        tr.add('drone', pad([key.deg(0, -1), key.deg(4, -1)], 4 * tr.beat, 0.6, bright=900), bar, 0)
        tr.add('bass', bass(key.deg(d, -1), 1.8 * tr.beat, 0.6, grit=0.3), bar, 0)
        tr.add('bass', bass(key.deg(d + 4, -1), 1.5 * tr.beat, 0.45, grit=0.3), bar, 2.5)
        pattern = [ch[0], ch[2], ch[1] + 12, ch[2], ch[0] + 12, ch[2], ch[1] + 12, ch[2]]
        for i, mm in enumerate(pattern):
            tr.add('marimba', marimba(mm + 12, 0.8, 0.55 if i % 2 == 0 else 0.4), bar, i * 0.5)
        for s in range(8):
            tr.add('perc', shaker(0.5 if s % 2 else 0.3), bar, s * 0.5 + (0.06 if s % 2 else 0))
        tr.add('perc', tom(key.deg(0, -1), 0.7), bar, 0)
        tr.add('perc', tom(key.deg(4, -1), 0.5), bar, 2.75)
    # Pentatonic flute line (degrees of natural minor avoiding 1 and 5).
    a = [(4, 1), (6, 1), (7, 2), (6, 0.5), (4, 0.5), (3, 1), (4, 3), (None, 1),
         (2, 1), (3, 1), (4, 1.5), (2, 0.5), (0, 2)]
    b = [(7, 1.5), (9, 0.5), (7, 1), (6, 1), (4, 2), (3, 1), (4, 1), (2, 1.5), (0, 0.5), (2, 1), (-1, 1),
         (0, 3), (None, 1)]
    play_melody(tr, 'lead', flute, key, a + b, 4, octave=1, vel=0.8, gap=0.98)
    play_melody(tr, 'lead', flute, key, a, 12, octave=1, vel=0.75, gap=0.98)
    x = tr.mix({'drone': 0.7, 'bass': 0.7, 'marimba': 0.55, 'perc': 0.6, 'lead': 0.7},
               {'drone': 0.4, 'marimba': 0.35, 'lead': 0.55, 'perc': 0.15})
    return master(x, -18)


def heroic():
    key = Key('C', 3, 'minor')
    tr = Track(bpm=132, bars=16)
    prog = [0, 5, 2, 6, 0, 5, 3, 4] * 2             # Cm Ab Eb Bb | Cm Ab Fm G
    for bar, d in enumerate(prog):
        ch = key.triad(d)
        if d == 4:  # make the dominant major for a heroic cadence
            ch = [ch[0], ch[1] + 1, ch[2]]
        for s in range(8):  # galloping string ostinato
            tr.add('strings', strings_stab(ch, 0.4 * tr.beat, 0.7 if s % 2 == 0 else 0.5), bar, s * 0.5)
        tr.add('pad', pad([m - 12 for m in ch], 4 * tr.beat, 0.7, bright=1200), bar, 0)
        tr.add('bass', bass(key.deg(d, -1), 0.9 * tr.beat, 0.8, grit=0.8), bar, 0)
        tr.add('bass', bass(key.deg(d, -1), 0.9 * tr.beat, 0.7, grit=0.8), bar, 1.5)
        tr.add('bass', bass(key.deg(d, -1), 0.9 * tr.beat, 0.7, grit=0.8), bar, 3)
        tr.add('drums', kick(1.0), bar, 0)
        tr.add('drums', kick(0.7), bar, 1.5)
        tr.add('drums', snare(0.9), bar, 1)
        tr.add('drums', snare(0.9), bar, 3)
        tr.add('drums', tom(key.deg(0, -1), 0.6), bar, 3.5)
        if bar % 8 == 7:
            for i in range(4):
                tr.add('drums', snare(0.5 + i * 0.12), bar, 2 + i * 0.5)
    theme = [(0, 1), (4, 1.5), (4, 0.5), (5, 1), (4, 2), (2, 1), (3, 1), (4, 3), (None, 1),
             (5, 1), (4, 1), (3, 1), (2, 1)]
    answer = [(7, 1.5), (6, 0.5), (5, 1), (4, 1), (5, 1.5), (4, 0.5), (3, 1), (2, 1),
              (3, 1), (2, 1), (1, 1), (-1, 1), (0, 4)]
    play_melody(tr, 'lead', brass, key, theme + answer, 4, octave=1, vel=0.95)
    play_melody(tr, 'lead', brass, key, theme, 12, octave=1, vel=0.9)
    x = tr.mix({'strings': 0.45, 'pad': 0.55, 'bass': 0.6, 'drums': 0.7, 'lead': 0.85},
               {'strings': 0.25, 'pad': 0.4, 'drums': 0.15, 'lead': 0.4})
    return master(x, -16)


TRACKS = {'frost': frost, 'volcano': volcano, 'mystic': mystic, 'heroic': heroic}


def write(name, x):
    pcm = np.clip(x * 32767, -32767, 32767).astype(np.int16)
    path = os.path.join(OUT, f'bgm_{name}.wav')
    with wave.open(path, 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    rms = 20 * np.log10(np.sqrt(np.mean(x ** 2)) + 1e-12)
    print(f'  bgm_{name}.wav  {len(x) / SR:5.1f}s  rms {rms:6.1f} dB  peak {np.abs(x).max():.2f}')


def main():
    names = sys.argv[1:] or list(TRACKS)
    for n in names:
        write(n, TRACKS[n]())


if __name__ == '__main__':
    main()
